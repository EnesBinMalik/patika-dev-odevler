export interface FactorLeaderInfo {
  factorKey: 'gdpPerCapita' | 'socialSupport' | 'healthyLifeExpectancy' | 'freedom' | 'trustGovCorruption' | 'generosity';
  factorName: string;
  factorNameTr: string;
  descriptionTr: string;
  worldAverage: number;
  topCountries: { country: string; flag: string; value: number; note: string }[];
  bottomCountries: { country: string; flag: string; value: number }[];
  correlationWithHappiness: number; // Pearson correlation approx
  importanceInsightTr: string;
}

export interface RegionalSummary {
  region: string;
  regionTr: string;
  countryCount: number;
  averageScore2017: number;
  averageScore2015: number;
  topCountry: string;
  topCountryScore: number;
  lowestCountry: string;
  lowestCountryScore: number;
  dominantFactor: string;
}

