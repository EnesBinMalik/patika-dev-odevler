export type ProductType = 'STANDARD' | 'PERISHABLE' | 'HAZARDOUS' | 'ELECTRONIC';

export interface BaseEntity {
  id: string;
  createdAt?: string;
  updatedAt?: string;
}

export interface Product extends BaseEntity {
  sku: string;
  name: string;
  category: string;
  productType: ProductType;
  stockQuantity: number;
  reorderThreshold: number; // Critical stock level
  unitPrice: number; // In TL (₺)
  shelfLocation: string; // e.g. "A-12-03"
  supplierId: string;
  unit: string; // "Adet", "Kutu", "Kg", "Litre"
  description: string;

  // Polymorphic custom attributes
  // PerishableProduct specifics:
  expiryDate?: string;
  storageTempCelsius?: number; // e.g. -18 or +4
  batchNumber?: string;

  // HazardousProduct specifics:
  hazardClass?: string; // e.g. "Sınıf 3 - Alevlenir Sıvı" or "Sınıf 8 - Aşındırıcı"
  unCode?: string; // e.g. "UN 1203"
  ventilationRequired?: boolean;

  // ElectronicProduct specifics:
  serialNumber?: string;
  warrantyMonths?: number;
  esdProtected?: boolean; // Elektrostatik Deşarj korumalı
}

export type MovementType = 'STOCK_IN' | 'STOCK_OUT' | 'ADJUSTMENT';

export interface StockMovement extends BaseEntity {
  sku: string;
  productName: string;
  movementType: MovementType;
  quantity: number;
  previousQuantity: number;
  newQuantity: number;
  reason: string; // "Tedarik Kabulü", "Satış Sevkiyatı", "Hasarlı Ürün İadesi", "Stok Sayımı Düzeltme"
  documentNo: string; // İrsaliye No / Fatura No
  operatorName: string;
  timestamp: string;
  notes?: string;
}

export interface Supplier extends BaseEntity {
  code: string; // e.g. "TED-001"
  name: string;
  contactPerson: string;
  phone: string;
  email: string;
  city: string;
  category: string;
  leadTimeDays: number; // Teslimat süresi (gün)
  reliabilityScore: number; // 1-100
  taxNumber: string;
}

export type OrderStatus = 'PENDING' | 'ORDERED' | 'IN_TRANSIT' | 'RECEIVED' | 'CANCELLED';

export interface PurchaseOrder extends BaseEntity {
  orderNumber: string;
  supplierId: string;
  supplierName: string;
  sku: string;
  productName: string;
  quantity: number;
  unitPrice: number;
  totalAmount: number;
  orderDate: string;
  expectedDate: string;
  status: OrderStatus;
  isAutoGenerated: boolean; // Otomatik kritik stok siparişi mi?
}

export interface StockAlertEvent {
  id: string;
  timestamp: string;
  sku: string;
  productName: string;
  eventType: 'CRITICAL_LEVEL' | 'DEPLETED' | 'RESTOCKED';
  currentQuantity: number;
  threshold: number;
  message: string;
  resolved: boolean;
}

export type SwingTheme = 'darcula' | 'nimbus' | 'classic' | 'windows';
