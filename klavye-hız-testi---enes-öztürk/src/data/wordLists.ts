/**
 * Generates a randomized list of words for the typing test
 */
export function generateRandomWords(language: 'tr' | 'en' = 'tr', count: number = 200): string[] {
  const source = language === 'tr' ? TURKISH_WORDS : ENGLISH_WORDS;
  const result: string[] = [];
  let lastWord = '';

  for (let i = 0; i < count; i++) {
    let candidate = '';
    let attempts = 0;
    do {
      const randomIndex = Math.floor(Math.random() * source.length);
      candidate = source[randomIndex];
      attempts++;
    } while (candidate === lastWord && attempts < 10);

    result.push(candidate);
    lastWord = candidate;
  }

  return result;
}
